// screen options (kept in EEPROM): type 0 = black tab (most red 1.8" boards), 1 = green tab, 2 = red tab
byte tftType = 0;
bool tftFlip = false;
byte tftOffX = 0, tftOffY = 0;

#ifdef __AVR__
  #define TFT_DC_LOW()   (PORTB &= ~_BV(1))   // D9
  #define TFT_DC_HIGH()  (PORTB |=  _BV(1))
  #define TFT_CS_LOW()   (PORTB &= ~_BV(2))   // D10
  #define TFT_CS_HIGH()  (PORTB |=  _BV(2))
  static inline void spiOut(uint8_t b) { SPDR = b; while (!(SPSR & _BV(SPIF))); }
  static inline void tftCmd(uint8_t c) { TFT_DC_LOW(); spiOut(c); TFT_DC_HIGH(); }
  static inline void tftData(uint8_t d) { spiOut(d); }
  static void tftPush(uint16_t c, uint16_t n) { uint8_t hi = c >> 8, lo = c; while (n--) { spiOut(hi); spiOut(lo); } }
  static inline void tftBegin() { TFT_CS_LOW(); }
  static inline void tftEnd() { TFT_CS_HIGH(); }
  static void tftWindow(uint8_t x, uint8_t y, uint8_t w, uint8_t h) {
    tftCmd(0x2A); tftData(0); tftData(x + tftOffX); tftData(0); tftData(x + w - 1 + tftOffX);
    tftCmd(0x2B); tftData(0); tftData(y + tftOffY); tftData(0); tftData(y + h - 1 + tftOffY);
    tftCmd(0x2C);
  }
#else
  // test bench: the screen is a picture in memory
  uint16_t fb[TFT_H][TFT_W];
  static uint8_t wx, wy, ww, wh, cx, cy;
  static inline void tftBegin() {}
  static inline void tftEnd() {}
  static inline void tftCmd(uint8_t) {}
  static inline void tftData(uint8_t) {}
  static void tftWindow(uint8_t x, uint8_t y, uint8_t w, uint8_t h) { wx = x; wy = y; ww = w; wh = h; cx = 0; cy = 0; }
  void simPixelTime(unsigned long n);
  static void tftPush(uint16_t c, uint16_t n) {
    simPixelTime(n);
    while (n--) {
      if (wy + cy < TFT_H && wx + cx < TFT_W) fb[wy + cy][wx + cx] = c;
      if (++cx >= ww) { cx = 0; cy++; }
    }
  }
#endif

